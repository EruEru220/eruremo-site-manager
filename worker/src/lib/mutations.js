/* ================================================================
   画像を変える操作（アップロード・削除）の非常停止スイッチ

   なぜ必要か：
     R2（画像の保管庫）は**使った分だけ費用がかかる**仕組みです。
     万一おかしな動きに気づいたとき、「画面は見られるけれど
     書き込みだけ止める」手段が要ります。

     `STAGING_LOCKED` は画面ごと全部止めてしまうので、
     様子を見ながら調べることができません。
     こちらは**書き込みだけ**を止め、読み出しは残します。

   いちばん大事な決まり：**"true" と完全に一致したときだけ許可します。**

     許可される：  "true"
     禁止される：  未設定 ／ "" ／ "false" ／ "TRUE" ／ "True" ／ "tru"
                   ／ " true "（空白つき） ／ その他すべての値

     設定を書き忘れた環境（将来の本番など）は、**自動的に書き込み禁止**に
     なります。書きまちがえても「書けなくなる」だけで済みます。
     大文字小文字も空白も吸収しません。**うっかり許可されないため**です。

   何を止めるか：
     止める … POST /api/media/upload ／ DELETE /api/media/item
     止めない … GET /api/media（一覧）／ GET・HEAD /media/…（読み出し）
                ／ GET /api/health（疎通確認）

   止まっているときは、**R2 に1回も触りません**（put も get も head も list も
   delete も 0回）。判定は R2 のバインディングを見るより前に行います。
   ================================================================ */

/**
 * 画像を変える操作をしてよいか。
 * **"true" という文字列そのもの**のときだけ true を返します。
 */
export function mutationsEnabled(env){
  return (env && env.MEDIA_MUTATIONS_ENABLED) === "true";
}
